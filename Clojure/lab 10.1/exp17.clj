(println "=== (1) Clojure List ===")
(def original-list '(10 20 30 40))
(println "Original list:            " original-list)
(println "First element:            " (first original-list))
(def rest-list (rest original-list))
(println "Rest of list:             " rest-list)
(def updated-list (conj original-list 5))
(println "After conj 5:             " updated-list)
(println "Original list (unchanged):" original-list)

(println "\n=== (2) Clojure Vector ===")
(def original-vec [10 20 30 40])
(println "Original vector:            " original-vec)
(println "Element at index 2:         " (get original-vec 2))
(println "Original count:             " (count original-vec))
(def updated-vec (conj original-vec 50))
(println "After conj 50:              " updated-vec)
(println "New vector count:           " (count updated-vec))
(println "Original vector (unchanged):" original-vec)

(println "\n=== (3) Clojure Map ===")
(def original-map {:name "Alice" :age 21 :course "CS"})
(println "Original map:            " original-map)
(println "Get :name:               " (get original-map :name))
(def assoc-map (assoc original-map :grade "A" :age 22))
(println "After assoc :grade/:age: " assoc-map)
(def dissoc-map (dissoc original-map :course))
(println "After dissoc :course:    " dissoc-map)
(println "Original map (unchanged):" original-map)

(println "\n=== (4) Clojure Set ===")
(def original-set #{:apple :banana :cherry})
(println "Original set:            " original-set)
(println "Contains :banana?:       " (contains? original-set :banana))
(println "Contains :mango?:        " (contains? original-set :mango))
(def conj-set (conj original-set :mango))
(println "After conj :mango:       " conj-set)
(def disj-set (disj original-set :banana))
(println "After disj :banana:      " disj-set)
(println "Original set (unchanged):" original-set)
