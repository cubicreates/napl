(import '[java.util ArrayList HashMap])

(println "=== (1) Java Static Methods ===")
(println "Math/abs (-42):          " (Math/abs -42))
(println "Math/sqrt 64:            " (Math/sqrt 64))
(println "System/currentTimeMillis:" (System/currentTimeMillis))

(println "\n=== (2) & (3) Java Objects and Instance Methods ===")
(def j-list (ArrayList.))
(.add j-list "Clojure")
(.add j-list "Java")
(.add j-list "JVM")
(println "ArrayList:       " j-list)
(println "ArrayList size:  " (.size j-list))
(println "ArrayList get(1):" (.get j-list 1))

(def j-map (new HashMap))
(.put j-map "name" "Alice")
(.put j-map "role" "Developer")
(println "HashMap:              " j-map)
(println "HashMap get(\"name\"):  " (.get j-map "name"))
(println "HashMap containsKey?: " (.containsKey j-map "role"))

(println "\n=== (4) Converting Between Clojure and Java Collections ===")
(def clj-vec [10 20 30 40])
(def vec-to-jlist (ArrayList. clj-vec))
(def jlist-to-vec (vec vec-to-jlist))
(println "Clojure vector -> ArrayList:" vec-to-jlist (type vec-to-jlist))
(println "ArrayList -> Clojure vector:" jlist-to-vec (type jlist-to-vec))

(def clj-map {"a" 1 "b" 2 "c" 3})
(def map-to-jmap (HashMap. clj-map))
(def jmap-to-map (into {} map-to-jmap))
(println "Clojure map -> HashMap:     " map-to-jmap (type map-to-jmap))
(println "HashMap -> Clojure map:     " jmap-to-map (type jmap-to-map))
